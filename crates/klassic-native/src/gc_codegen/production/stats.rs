pub(crate) fn stat_offsets() -> StatOffsets {
    StatOffsets {
        metadata: super::metadata::report_offsets().map(|offset| field(offset as usize)),
        large_pages: super::large_pages::report_offsets().map(|offset| field(offset as usize)),
        trace: super::trace::report_offsets().map(|offset| field(offset as usize)),
        mutator_time: super::mutator_time::report_offsets().map(field),
        native_io: [
            super::native_io::ENTRIES,
            super::native_io::EXITS,
            super::native_io::CHUNKS,
            super::native_io::BUFFER_WRITES,
        ]
        .map(field),
        large_object: super::large_object::report_offsets().map(|offset| field(offset as usize)),
        heap_uncommit_delay_ns: field(super::commit::DELAY_NS),
        heap_minimum: field(super::commit::report_offset(super::commit::MINIMUM)),
        heap_committed: field(super::commit::report_offset(super::commit::COMMITTED)),
        heap_peak: field(super::commit::report_offset(super::commit::PEAK)),
        heap_commits: field(super::commit::report_offset(super::commit::COMMITS)),
        heap_recommits: field(super::commit::report_offset(super::commit::RECOMMITS)),
        heap_uncommits: field(super::commit::report_offset(super::commit::UNCOMMITS)),
        heap_pretouched: field(super::commit::report_offset(super::commit::PRETOUCHED)),
        heap_capacity_bytes: field(RT_HEAP_CAPACITY_BYTES),
        heap_soft_maximum: field(offset_of!(super::Runtime, heap_soft_maximum)),
        old_limit_bytes: field(RT_OLD_LIMIT_BYTES),
        old_charged_bytes: field(RT_OLD_CHARGED_BYTES),
        young_limit_pages: field(RT_YOUNG_LIMIT_PAGES),
        old_run_count: field(super::old_runs::COUNT),
        old_run_switches: field(super::old_runs::SWITCHES),
        old_capacity_pages: field(super::pool::OLD_PAGES),
        pool_reduced_old_runs: field(super::pool::REDUCED_OLD_RUNS),
        pool_runs: field(super::pool::CLAIMS),
        pool_released_pages: field(super::pool::RELEASED),
        pool_role_transfers: field(super::pool::TRANSFERS),
        young_capacity_pages: field(capacity::ACTIVE),
        young_requested_pages: field(capacity::REQUESTED),
        young_protected_bytes: field(capacity::SEALED),
        young_copy_reserve_pages: field(capacity::RESERVE),
        young_capacity_clamps: field(capacity::CLAMPS),
        young_capacity_grows: field(capacity::GROWS),
        young_capacity_shrinks: field(capacity::SHRINKS),
        young_capacity_samples: field(capacity::SAMPLES),

        young_mark_elapsed_ns: field(start_policy::DURATION_NS),
        start_target_pages: field(start_policy::TARGET),
        allocation_bytes_per_ms: field(start_policy::ALLOC_RATE),
        young_mark_units_per_ms: field(start_policy::MARK_RATE),
        start_rate_samples: field(start_policy::RATE_SAMPLES),
        start_mark_samples: field(start_policy::MARK_SAMPLES),
        start_target_updates: field(start_policy::UPDATES),
        start_invalid_samples: field(start_policy::INVALID),
        last_mark_work_units: field(start_policy::MARK_UNITS),

        fresh_allocated_bytes: field(old_policy::ALLOCATED),
        collections: field(RT_COLLECTIONS),
        full_collections: field(RT_FULL_COLLECTIONS),
        healed: field(RT_HEALED),
        promoted: field(RT_PROMOTED),
        allocated_bytes: field(RT_CTX + offset_of!(MutatorContext, allocated_bytes)),
        pages_used: field(RT_PAGES_USED),
        objects: field(RT_OBJECTS),
        published: field(RT_VERIFIED),
        worker_scanned: field(RT_WORKER_SCANNED),
        worker_copies: field(RT_WORKER_COPIES),
        worker_lost: field(RT_WORKER_LOST),
        mutator_copies: field(RT_MUTATOR_COPIES),
        mutator_lost: field(RT_MUTATOR_LOST),
        mark_cycles: field(RT_MARK_CYCLES),
        marked: field(RT_MARKED),
        mark_drains: field(RT_MARK_DRAINS),
        unmarked_copied: field(RT_UNMARKED),
        remset_dropped: field(RT_REMSET_DROPPED),
        remset_len: field(RT_REMSET_LEN),
        remset_flips: field(RT_REMSET_FLIPS),
        remset_flipped: field(RT_REMSET_FLIPPED),
        remset_kept: field(RT_REMSET_KEPT),
        allocation_stalls: field(RT_ALLOCATION_STALLS),
        old_prediction_clamps: field(old_policy::CLAMPS),
        tenuring_threshold: field(tenuring::THRESHOLD),
        tenuring_frozen: field(tenuring::FROZEN),
        tenuring_updates: field(tenuring::UPDATES),
        tenuring_young_samples: field(tenuring::YOUNG_SAMPLES),
        tenuring_full_samples: field(tenuring::FULL_SAMPLES),
        young_survivor_bytes: field(tenuring::LAST_YOUNG),
        young_promoted_winner_bytes: field(tenuring::LAST_PROMOTED),
        old_target_bytes: field(old_policy::TARGET),
        old_retained_bytes: field(old_policy::RETAINED),
        old_promotion_ema: field(old_policy::EMA),
        old_allocation_budget: field(old_policy::BUDGET),
        old_full_samples: field(old_policy::FULL),
        old_young_samples: field(old_policy::YOUNG),
        old_target_updates: field(old_policy::UPDATES),
        old_deferred: field(old_policy::DEFERRED),
        old_periodic_requests: field(old_policy::PERIODIC),
        old_pressure_requests: field(old_policy::PRESSURE),
        old_planned_cycles: field(old_cycle::PLANNED),
        old_cycle_checks: field(old_cycle::CHECKS),
        old_cycle_retries: field(old_cycle::RETRIES),
        young_mark_cycles: field(young_mark::EPOCH),
        young_marked: field(young_mark::MARKED),
        young_worker_units: field(young_mark::WORKER_UNITS),
        young_mark_waits: field(young_mark::WAITS),
        young_unmarked_copied: field(young_mark::UNMARKED),
    }
}

fn field(offset: usize) -> RuntimeField {
    RuntimeField(offset)
}
