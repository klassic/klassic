//! Runs the C garbage collector's own unit tests under
//! separate ASan+UBSan and TSan builds (`runtime/gc/run_tests.sh`) as part of
//! `cargo test`. Part of the LLVM backend migration
//! (`docs/llvm-backend-plan.md`, M6): the GC is C now, so it gets a
//! memory sanitizer the hand-emitted collector never could. This required
//! Linux validation fails if a C compiler is absent; production direct builds
//! remain independent of an external compiler.
#![cfg(all(target_os = "linux", target_arch = "x86_64"))]

use std::process::Command;

fn find_cc() -> Option<String> {
    if let Ok(explicit) = std::env::var("KLASSIC_CLANG") {
        return Some(explicit);
    }
    [
        "clang-18", "clang-17", "clang-16", "clang-15", "clang", "cc",
    ]
    .into_iter()
    .find(|name| {
        Command::new(name)
            .arg("--version")
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok_and(|status| status.success())
    })
    .map(str::to_owned)
}

